import assert from 'node:assert/strict';
import { fixture } from './browser-fixture.mjs';
const call = (f, path, method = 'GET') => f.response(method, new URL('http://fixture.local/api' + path));
const payment = fixture('payment');
assert.equal(call(payment, '/orders/phase19-browser-order')[1].status, 'PENDING_PAYMENT');
assert.equal(call(payment, '/orders/phase19-browser-order/pay', 'POST')[1].paymentAttempt.status, 'PROCESSING');
payment.state.terminal = true;
assert.equal(call(payment, '/payment-attempts/phase19-browser-attempt')[1].status, 'SUCCEEDED');
assert.equal(call(payment, '/orders/phase19-browser-order')[1].status, 'PAID');
const refund = fixture('refund');
assert.equal(call(refund, '/orders/phase19-browser-order')[1].refundEligibility.eligible, true);
assert.equal(call(refund, '/orders/phase19-browser-order/refunds', 'POST')[1].pollAfterMs, 5000);
refund.state.terminal = true;
assert.equal(call(refund, '/orders/phase19-browser-order')[1].buyerRefund.status, 'SUCCEEDED');
assert.equal(call(refund, '/orders/phase19-browser-order')[1].status, 'CANCELLED');
const checkout = fixture('submitting');
assert.equal(call(checkout, '/checkout-sessions')[1][0].status, 'SUBMITTING');
checkout.state.terminal = true;
assert.equal(call(checkout, '/checkout-sessions/phase19-browser-checkout/confirm', 'POST')[1].checkoutSession.status, 'RESERVED');
const seat = fixture('seat');
assert.equal(call(seat, '/sessions/phase19-browser-session')[1].admission.state, 'NOT_REQUIRED');
const snapshot = call(seat, '/sessions/phase19-browser-session/seat-availability?zone=Zone-3')[1];
assert.equal(snapshot.seats.length, 1000);
assert.equal(snapshot.zones.reduce((n, z) => n + z.total, 0), 5000);
const delta = call(seat, '/sessions/phase19-browser-session/seat-availability?zone=Zone-3&since=1-0&generation=phase19-browser-generation')[1];
assert.equal(delta.cursor, snapshot.cursor); assert.equal(delta.mode, 'delta'); assert.equal(delta.pollAfterMs, 5000);
assert.equal(call(seat, '/unexpected')[0], 404);
call(seat, '/auth/logout', 'POST');
assert.equal(call(seat, '/auth/me')[0], 401); assert.equal(call(seat, '/notifications')[0], 401);
console.log('Phase19 controlled browser fixture assertions passed');
